def test_every_published_page_is_reachable_from_the_sidebar():
    """Navigation must not silently drop a page.

    Building the sidebar explicitly fixed the "Evidence, Evidence, Evidence"
    tree and lost something else: the builder recursed into directories only,
    so every `LANDSCAPE.md`, every standard, every research pass, and all three
    compute-lane guides were published, linked from prose, and unreachable from
    navigation. Only `runs/`, `core/`, and `prod/` are supposed to be
    off-tree — they are evidence and implementation, cited from the lesson that
    owns them.
    """
    import json

    sidebar_file = ROOT / "site" / "sidebars.generated.json"
    docs = ROOT / "site" / "docs"
    if not sidebar_file.is_file() or not docs.is_dir():
        return  # site not synced in this environment

    listed: set[str] = set()

    def walk(node) -> None:
        if isinstance(node, list):
            for item in node:
                walk(item)
            return
        if not isinstance(node, dict):
            return
        if node.get("type") == "doc":
            listed.add(node["id"])
        link = node.get("link") or {}
        if link.get("type") == "doc":
            listed.add(link["id"])
        for item in node.get("items", []):
            walk(item)

    walk(json.loads(sidebar_file.read_text()))

    def route(doc_id: str) -> str:
        return doc_id.removesuffix("/index")

    listed = {route(doc_id) for doc_id in listed}
    missing = []
    for page in sorted(docs.rglob("*.md*")):
        relative = page.relative_to(docs)
        if set(relative.parts) & SYNC_DOCS.UNLISTED_DIRS:
            continue
        doc_id = route(relative.with_suffix("").as_posix())
        if doc_id in ("index", *listed):
            continue
        missing.append(doc_id)

    assert not missing, "published but unreachable from the sidebar:\n  " + "\n  ".join(
        missing
    )


def test_no_published_page_is_an_orphan_in_prose():
    """Reachable from the sidebar is not the same as reached by a reader.

    The test above proves every page is listed in navigation. It passed while
    ten pages had no inbound link from any sentence anywhere -- seven
    `LANDSCAPE.md` tables, a branch index, and a sub-lesson --
    which meant a reader following the causal spine of the curriculum never
    learned they existed. The `LANDSCAPE.md` case was the sharpest: AGENTS.md
    requires each one to name two production alternatives, and not one chapter
    pointed at the table it was requiring.
    """
    sections = (*SECTIONS_WITH_CHAPTERS, "reference")
    pages = [
        page
        for section in sections
        for page in sorted((ROOT / section).rglob("*.md"))
        if not {"core", "prod", "runs", "cache"} & set(page.parts)
    ]

    def page_id(path: Path) -> str:
        if path.name == "README.md":
            return path.parent.relative_to(ROOT).as_posix()
        return path.relative_to(ROOT).with_suffix("").as_posix()

    ids = {page_id(p) for p in pages}
    # Root docs route into the sections and count as prose like any chapter.
    sources = pages + [ROOT / "README.md", ROOT / "AGENTS.md"]
    linked: set[str] = set()
    for source in sources:
        if not source.is_file():
            continue
        for target in re.findall(r"\]\((?!http|#)([^)#]+)", source.read_text()):
            old_dir = str(Path(SYNC_DOCS.old_location(source.relative_to(ROOT).as_posix())).parent)
            try:
                resolved = (ROOT / old_dir / target).resolve().relative_to(ROOT.resolve())
            except ValueError:
                continue  # points outside the repository
            text = resolved.as_posix().rstrip("/")
            text = (
                text[: -len("/README.md")]
                if text.endswith("/README.md")
                else text.removesuffix(".md")
            )
            for old, new in SYNC_DOCS.RENAMES.items():
                if text == old or text.startswith(old + "/"):
                    text = new + text[len(old):]
                    break
            if text != page_id(source):
                linked.add(text)

    orphans = sorted(ids - linked)
    assert not orphans, (
        "published but linked from no sentence in the repository; a page only "
        "the sidebar knows about is a page nobody reads:\n  " + "\n  ".join(orphans)
    )


def test_angle_brackets_survive_inline_code_verbatim():
    """MDX does not parse JSX inside a code span, so `<` there needs no escape.

    Escaping it anyway does not round-trip: markdown renders a code span's
    contents literally, entities included, so the reader sees the eight
    characters `&lt;` instead of a `<`. The SFT lesson's chat template shipped
    that way — in the chapter arguing the template is a learned convention
    rather than magic syntax, which is the worst possible place for it.
    """
    prose = "The bytes `<|im_start|>` mark a turn, and <1,000 lines is prose."

    escaped = SYNC_DOCS.escape_mdx(prose)

    assert "`<|im_start|>`" in escaped, "inline code must be left alone"
    assert "&lt;1,000" in escaped, "bare prose still needs escaping"
    assert "&lt;|im_start|" not in escaped


def test_fenced_and_inline_code_are_both_stepped_over():
    document = (
        "prose with <1,000 lines in it\n"
        "```python\n"
        "if a < b:  # a fence is untouched\n"
        "```\n"
        "trailing `a < b` span and a bare < here"
    )

    escaped = SYNC_DOCS.escape_mdx(document)

    assert "&lt;1,000" in escaped
    assert "if a < b:" in escaped
    assert "`a < b`" in escaped
    assert "a bare &lt; here" in escaped


def test_a_tag_shaped_token_in_prose_is_left_for_mdx_to_read_as_jsx():
    """`<` followed by a letter is deliberately not escaped.

    It is genuinely ambiguous — `<Widget />` in a lesson is a component the page
    means to render. The rule is therefore that a tag-shaped token in prose is
    treated as a tag, and anything that must appear literally goes in backticks.
    Documented because the escaping docstring used to claim `<UNK>` was covered
    here, and it never was.
    """
    assert SYNC_DOCS.escape_mdx("a bare <UNK> token") == "a bare <UNK> token"


def test_every_chapter_appears_in_at_least_one_topic():
    """`site/topics.mdx` is the only index that cuts across sections.

    The sidebar groups chapters by which section owns them, which answers
    "where does a new chapter belong" and not "where is the chapter about the
    thing I am stuck on". Read-by-topic answers the second question -- and it
    silently stopped answering it, because nothing enforced coverage: it was
    written when the repository ended at mission 04 and, by the time anyone
    checked, it named 62 of 129 chapters. Missions 05-09 and the whole of
    `infra/` were unfindable from any cross-cutting page.

    Section roots are exempt: they are the sidebar's own top-level entries and
    the topic page links into their chapters instead.
    """
    topics = (ROOT / "site" / "topics.mdx").read_text()
    linked = {
        route.strip("/")
        for route in re.findall(r"\(/playground/([^)]*?)\)", topics)
    }

    missing = []
    for section in SECTIONS_WITH_CHAPTERS:
        for readme in sorted((ROOT / section).rglob("README.md")):
            chapter = readme.parent.relative_to(ROOT)
            if set(chapter.parts) & SYNC_DOCS.UNLISTED_DIRS:
                continue
            route = chapter.as_posix()
            if route == section or route in linked:
                continue
            missing.append(route)

    assert not missing, (
        "published but named by no topic in site/topics.mdx:\n  "
        + "\n  ".join(missing)
    )


def test_read_by_topic_links_all_resolve_to_a_real_chapter():
    """A topic entry that points at nothing is worse than a missing one.

    The coverage test above only proves every chapter is named somewhere. It
    cannot catch a link to a route that was renamed or never existed, which is
    exactly what happens when a chapter directory is renumbered.
    """
    topics = (ROOT / "site" / "topics.mdx").read_text()
    broken = []
    for route in re.findall(r"\(/playground/([^)]+?)\)", topics):
        target = ROOT / route.strip("/")
        if (target / "README.md").is_file() or target.with_suffix(".md").is_file():
            continue
        broken.append(route)

    assert not broken, "site/topics.mdx points at routes that do not exist:\n  " + (
        "\n  ".join(broken)
    )


def test_only_a_lesson_carries_a_build_status_badge():
    """The sidebar badge marks the exception, not the rule.

    It used to append "· verified" to every backed chapter, which tagged 97 of
    129 entries with the same seven characters: a label that fires almost
    always discriminates nothing and costs every entry the width. Inverted, it
    marks drafts -- but only on a lesson. A section, branch, or mission index
    has no `runs/` because it never promised a measurement, and "Foundations ·
    draft" reads as though the whole section were unfinished.
    """
    assert SYNC_DOCS.is_lesson(Path("01-language-model/eval/eval-gates"))
    assert not SYNC_DOCS.is_lesson(Path("foundations"))
    assert not SYNC_DOCS.is_lesson(Path("01-language-model"))

    docs = ROOT / "site" / "docs"
    if not docs.is_dir():
        return  # site not synced in this environment

    badged = [
        page.relative_to(docs).as_posix()
        for page in sorted(docs.rglob("index.md*"))
        if "· draft" in page.read_text()[:400]
    ]
    for page in badged:
        chapter = Path(page).parent
        source = ROOT / chapter
        assert SYNC_DOCS.is_lesson(source), f"{page} is an index, not a lesson"
