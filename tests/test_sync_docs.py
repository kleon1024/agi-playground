import importlib.util
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SYNC_DOCS_PATH = ROOT / "site" / "sync-docs.py"

SPEC = importlib.util.spec_from_file_location("sync_docs", SYNC_DOCS_PATH)
assert SPEC is not None and SPEC.loader is not None
SYNC_DOCS = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(SYNC_DOCS)


def test_relative_lesson_links_become_absolute_public_routes():
    source = Path("foundations/README.md")
    markdown = (
        "[loop](01-first-training-loop/) "
        "[training](../platform/training/README.md#next)"
    )

    rewritten = SYNC_DOCS.rewrite_links(markdown, source)

    assert "[loop](/playground/foundations/01-first-training-loop)" in rewritten
    assert "[training](/playground/platform/training#next)" in rewritten


def test_chapter_order_comes_from_the_manifest_not_the_directory_name():
    """The nav once read 02, 07, 06, 03 because positions were never emitted.

    Docusaurus sorts an autogenerated sidebar alphabetically by filename, so
    `platform/training/` sorted after `platform/serving/` no matter what the
    headings said. Position now comes from `standards/curriculum-order.txt`.
    """
    order = SYNC_DOCS.CHAPTER_ORDER

    assert order["platform/data"] < order["platform/training"]
    assert order["platform/training"] < order["platform/serving"]
    assert order["platform/serving"] < order["platform/evaluation-observability"]
    assert SYNC_DOCS.order_from(Path("platform/training/README.md")) == order[
        "platform/training"
    ]


