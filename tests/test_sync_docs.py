def test_every_chapter_directory_is_listed():
    """A chapter missing from the manifest would sort into the default bucket.

    That is the drift this file exists to prevent: content added without the
    table of contents noticing.
    """
    expected = set(SYNC_DOCS.CHAPTER_ORDER)
    for section in ("platform", "capabilities"):
        for readme in sorted((ROOT / section).rglob("README.md")):
            chapter = readme.parent.relative_to(ROOT).as_posix()
            if any(part in ("core", "prod", "runs") for part in Path(chapter).parts):
                continue
            if SYNC_DOCS.DIR_NUM_RE.match(readme.parent.name):
                continue  # a sub-lesson, ordered by its own directory prefix
            assert chapter in expected or chapter == "platform/safety-governance", (
                f"{chapter} has a README but is not in standards/curriculum-order.txt"
            )


def test_headings_do_not_carry_their_own_chapter_number():
    """Inserting a chapter must stay a one-line change.

    A hand-written "# 03 — Pretraining" makes every insertion an O(n) edit
    across headings and prose, with nothing failing when one is missed.
    """
    offenders = []
    for section in ("foundations", "platform", "capabilities", "missions"):
        for path in sorted((ROOT / section).rglob("*.md")):
            first = next(
                (ln for ln in path.read_text().splitlines() if ln.startswith("# ")), ""
            )
            # `# Stage 08 — Serving` is the same defect as `# 03 — Pretraining`
            # wearing a word in front of it, and it slipped past the first
            # version of this pattern.
            if re.match(r"^# (?:stage|chapter|part|lesson|step)?\s*\d+\s*[—–:-]\s", first, re.IGNORECASE):
                offenders.append(f"{path.relative_to(ROOT)}: {first}")
    assert not offenders, (
        "these headings hard-code a chapter number; the number is generated from "
        "standards/curriculum-order.txt:\n  " + "\n  ".join(offenders)
    )


