def test_section_index_lists_are_in_curriculum_order():
    """A section index once read in order only by accident, because every
    title began with its position ("02 — Data") and the listing sorted
    alphabetically. Dropping the visible numbers turned it into alphabetical
    nonsense.
    """
    index = ROOT / "site" / "docs" / "foundations" / "index.md"
    if not index.is_file():
        return  # site not synced in this environment
    # No `$` anchor: each entry now carries its level and reading time after
    # the link. This test is about ordering, not about the line's shape.
    listed = re.findall(r"^- \[[^\]]+\]\(([^)/]+)/\)", index.read_text(), re.MULTILINE)
    positions = [
        SYNC_DOCS.order_from(Path("foundations") / name / "README.md") for name in listed
    ]
    assert positions == sorted(positions), (
        "site/docs/foundations/index.md is not in curriculum order:\n  "
        + "\n  ".join(f"{n} (position {p})" for n, p in zip(listed, positions))
    )


